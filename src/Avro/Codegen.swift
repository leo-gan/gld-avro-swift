private let swiftKeywords: Set<String> = [
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import",
    "init", "inout", "internal", "let", "open", "operator", "private", "protocol", "public",
    "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "continue",
    "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat",
    "return", "switch", "where", "while", "as", "Any", "catch", "false", "is", "nil", "super",
    "self", "Self", "throw", "throws", "true", "try", "async", "await", "some", "each",
    "borrowing", "consuming", "package", "isolated", "nonisolated", "Type", "Protocol",
]

public func emitSwift(pool: SchemaPool) throws -> [(name: String, source: String)] {
    let emitter = SwiftEmitter(pool: pool)
    return try emitter.emit()
}

final class SwiftEmitter {
    let pool: SchemaPool
    var scc: [Int: Set<Int>] = [:]
    var unionNames: [Int: String] = [:]
    var unionOwners: [Int: Int] = [:]
    var serial = 0

    init(pool: SchemaPool) { self.pool = pool }

    func emit() throws -> [(name: String, source: String)] {
        scc = strongComponents(pool)
        for (id, node) in pool.nodes.enumerated() where node.kind == .record && node.complete {
            let group = scc[id] ?? [id]
            for field in node.fields {
                if pool.nodes[field.typeId].kind == .record && group.contains(field.typeId) {
                    throw CodegenError("non-optional recursive field \(node.name).\(field.name)")
                }
                try rejectFullyRecursiveUnion(field.typeId, owner: id, path: "\(node.name).\(field.name)")
                discover(field.typeId, name: "\(typeName(id))_\(typePiece(field.name))", owner: id)
            }
        }
        if pool.root >= 0 {
            discover(pool.root, name: "AvroRootUnion", owner: nil)
        }
        var files: [(String, String)] = []
        var emitted = Set<Int>()
        for (id, node) in pool.nodes.enumerated() where node.complete {
            if emitted.contains(id) { continue }
            switch node.kind {
            case .record:
                files.append((typeName(id) + ".swift", try emitRecord(id)))
                emitted.insert(id)
            case .enumeration:
                files.append((typeName(id) + ".swift", try emitEnum(id)))
                emitted.insert(id)
            case .fixed:
                files.append((typeName(id) + ".swift", try emitFixed(id)))
                emitted.insert(id)
            case .union:
                if optionalInfo(id) == nil, let name = unionNames[id] {
                    files.append((name + ".swift", try emitUnion(id, name: name, owner: unionOwners[id])))
                    emitted.insert(id)
                }
            default:
                break
            }
        }
        return files
    }

    func rejectFullyRecursiveUnion(_ id: Int, owner: Int, path: String) throws {
        guard pool.nodes[id].kind == .union, optionalInfo(id) == nil else { return }
        let group = scc[owner] ?? []
        let branches = pool.nodes[id].branchIds
        if !branches.isEmpty && branches.allSatisfy({ pool.nodes[$0].kind == .record && group.contains($0) }) {
            throw CodegenError("union \(path) has no non-recursive branch")
        }
    }

    func discover(_ id: Int, name: String, owner: Int?) {
        let node = pool.nodes[id]
        switch node.kind {
        case .union:
            if optionalInfo(id) != nil {
                if let value = optionalInfo(id)?.valueId {
                    discover(value, name: name, owner: owner)
                }
            } else if unionNames[id] == nil {
                unionNames[id] = name
                if let owner { unionOwners[id] = owner }
            }
            for branch in node.branchIds {
                discover(branch, name: name + "Branch", owner: owner)
            }
        case .array:
            discover(node.itemId, name: name + "Item", owner: owner)
        case .map:
            discover(node.valueId, name: name + "Value", owner: owner)
        default:
            break
        }
    }

    func emitRecord(_ id: Int) throws -> String {
        let node = pool.nodes[id]
        let name = typeName(id)
        var lines: [String] = []
        lines.append("// Generated by gld-avrogen-swift. Do not edit.")
        lines.append("import Avro")
        lines.append("")
        lines.append("public struct \(name): AvroCodable {")
        for field in node.fields {
            lines.append("    public var \(fieldIdent(field.name)): \(rendered(field.typeId, owner: id))")
        }
        lines.append("")
        lines.append("    public init() {")
        for field in node.fields {
            lines.append("        self.\(fieldIdent(field.name)) = \(try zero(field.typeId, owner: id))")
        }
        lines.append("    }")
        lines.append("")
        let params = node.fields.map { "\($0.name == fieldIdent($0.name) ? fieldIdent($0.name) : fieldIdent($0.name)): \(rendered($0.typeId, owner: id))" }
        let args = node.fields.map { field in
            let ident = fieldIdent(field.name)
            return "\(ident): \(ident)"
        }
        lines.append("    public init(\(params.joined(separator: ", "))) {")
        for field in node.fields {
            let ident = fieldIdent(field.name)
            lines.append("        self.\(ident) = \(ident)")
        }
        lines.append("    }")
        lines.append("")
        lines.append("    public func encodedByteLength() -> Int {")
        lines.append("        var total = 0")
        for field in node.fields {
            lines.append(contentsOf: try lengthLines(field.typeId, expr: fieldIdent(field.name), indent: "        ", owner: id))
        }
        lines.append("        return total")
        lines.append("    }")
        lines.append("")
        lines.append("    public func encode(into encoder: inout BinaryEncoder) {")
        for field in node.fields {
            lines.append(contentsOf: try encodeLines(field.typeId, expr: fieldIdent(field.name), indent: "        ", owner: id))
        }
        lines.append("    }")
        lines.append("")
        lines.append("    public static func decode(from decoder: inout BinaryDecoder) throws -> \(name) {")
        for field in node.fields {
            lines.append(contentsOf: try decodeLines(field.typeId, dest: fieldIdent(field.name), indent: "        ", owner: id))
        }
        lines.append("        return \(name)(\(args.joined(separator: ", ")))")
        lines.append("    }")
        lines.append("")
        lines.append("    public static var schemaJSON: String { \(swiftLiteral(emitSchemaJSON(pool, root: id))) }")
        lines.append("")
        lines.append("    public static func fromResolved(_ value: AvroValue) throws -> \(name) {")
        lines.append("        let fields = try AvroResolved.record(value, count: \(node.fields.count))")
        for (index, field) in node.fields.enumerated() {
            lines.append(contentsOf: try resolvedLines(field.typeId, valueExpr: "fields[\(index)]", dest: fieldIdent(field.name), indent: "        ", owner: id))
        }
        lines.append("        return \(name)(\(args.joined(separator: ", ")))")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    func emitEnum(_ id: Int) throws -> String {
        let node = pool.nodes[id]
        let name = typeName(id)
        var lines: [String] = []
        lines.append("// Generated by gld-avrogen-swift. Do not edit.")
        lines.append("import Avro")
        lines.append("")
        lines.append("public enum \(name): String, AvroCodable {")
        for symbol in node.symbols {
            lines.append("    case \(caseIdent(symbol)) = \(swiftLiteral(symbol))")
        }
        lines.append("")
        lines.append("    public init() { self = .\(caseIdent(node.symbols[0])) }")
        lines.append("")
        lines.append("    public var symbolIndex: Int32 {")
        lines.append("        switch self {")
        for (index, symbol) in node.symbols.enumerated() {
            lines.append("        case .\(caseIdent(symbol)): return \(index)")
        }
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public func encodedByteLength() -> Int { AvroBinary.intLength(symbolIndex) }")
        lines.append("    public func encode(into encoder: inout BinaryEncoder) { encoder.writeInt(symbolIndex) }")
        lines.append("    public static func decode(from decoder: inout BinaryDecoder) throws -> \(name) {")
        lines.append("        switch try decoder.readInt() {")
        for (index, symbol) in node.symbols.enumerated() {
            lines.append("        case \(index): return .\(caseIdent(symbol))")
        }
        lines.append("        default: throw DecodeError(kind: .badEnum, offset: decoder.offset, field: 0)")
        lines.append("        }")
        lines.append("    }")
        lines.append("    public static var schemaJSON: String { \(swiftLiteral(emitSchemaJSON(pool, root: id))) }")
        lines.append("    public static func fromResolved(_ value: AvroValue) throws -> \(name) {")
        lines.append("        switch try AvroResolved.symbol(value) {")
        for symbol in node.symbols {
            lines.append("        case \(swiftLiteral(symbol)): return .\(caseIdent(symbol))")
        }
        lines.append("        default: throw DecodeError(kind: .badEnum, offset: 0, field: 0)")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    func emitFixed(_ id: Int) throws -> String {
        let name = typeName(id)
        let size = pool.nodes[id].size
        return """
        // Generated by gld-avrogen-swift. Do not edit.
        import Avro

        public struct \(name): AvroCodable {
            public static let size = \(size)
            public var bytes: [UInt8]
            public init() { self.bytes = [UInt8](repeating: 0, count: \(size)) }
            public init(bytes: [UInt8]) { self.bytes = bytes }
            public func encodedByteLength() -> Int { \(size) }
            public func encode(into encoder: inout BinaryEncoder) {
                if bytes.count == \(size) {
                    encoder.writeFixed(bytes)
                } else {
                    var tmp = [UInt8](repeating: 0, count: \(size))
                    for index in 0..<min(\(size), bytes.count) { tmp[index] = bytes[index] }
                    encoder.writeFixed(tmp)
                }
            }
            public static func decode(from decoder: inout BinaryDecoder) throws -> \(name) {
                try \(name)(bytes: decoder.readFixed(\(size)))
            }
            public static var schemaJSON: String { \(swiftLiteral(emitSchemaJSON(pool, root: id))) }
            public static func fromResolved(_ value: AvroValue) throws -> \(name) {
                try \(name)(bytes: AvroResolved.fixed(value, size: \(size)))
            }
        }

        """
    }

    func emitUnion(_ id: Int, name: String, owner: Int?) throws -> String {
        let branches = pool.nodes[id].branchIds
        var used = Set<String>()
        var cases: [(name: String, type: String?, index: Int, typeId: Int)] = []
        for (index, branch) in branches.enumerated() {
            let caseName = freshCase(branch, index: index, used: &used)
            let payload = pool.nodes[branch].kind == .null ? nil : rendered(branch, owner: owner)
            cases.append((caseName, payload, index, branch))
        }
        guard let zeroCase = cases.first(where: { !branchRecursive($0.typeId, owner: owner) }) else {
            throw CodegenError("union \(name) has no non-recursive branch")
        }
        var lines: [String] = []
        lines.append("// Generated by gld-avrogen-swift. Do not edit.")
        lines.append("import Avro")
        lines.append("")
        lines.append("public enum \(name): AvroCodable {")
        for item in cases {
            if let type = item.type {
                lines.append("    case \(item.name)(\(type))")
            } else {
                lines.append("    case \(item.name)")
            }
        }
        lines.append("")
        lines.append("    public init() {")
        if zeroCase.type != nil {
            lines.append("        self = .\(zeroCase.name)(\(try zero(zeroCase.typeId, owner: owner)))")
        } else {
            lines.append("        self = .\(zeroCase.name)")
        }
        lines.append("    }")
        lines.append("")
        lines.append("    public func encodedByteLength() -> Int {")
        lines.append("        switch self {")
        for item in cases {
            if item.type != nil {
                lines.append("        case .\(item.name)(let payload):")
                lines.append("            var total = AvroBinary.longLength(\(item.index))")
                lines.append(contentsOf: try lengthLines(item.typeId, expr: valueOf(item.typeId, expr: "payload", owner: owner), indent: "            ", owner: owner))
                lines.append("            return total")
            } else {
                lines.append("        case .\(item.name):")
                lines.append("            return AvroBinary.longLength(\(item.index))")
            }
        }
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public func encode(into encoder: inout BinaryEncoder) {")
        lines.append("        switch self {")
        for item in cases {
            if item.type != nil {
                lines.append("        case .\(item.name)(let payload):")
                lines.append("            encoder.writeLong(\(item.index))")
                lines.append(contentsOf: try encodeLines(item.typeId, expr: valueOf(item.typeId, expr: "payload", owner: owner), indent: "            ", owner: owner))
            } else {
                lines.append("        case .\(item.name):")
                lines.append("            encoder.writeLong(\(item.index))")
            }
        }
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public static func decode(from decoder: inout BinaryDecoder) throws -> \(name) {")
        lines.append("        switch try decoder.readLong() {")
        for item in cases {
            lines.append("        case \(item.index):")
            if item.type != nil {
                lines.append(contentsOf: try decodeLines(item.typeId, dest: "payload", indent: "            ", owner: owner))
                lines.append("            return .\(item.name)(\(boxWrap(item.typeId, expr: "payload", owner: owner)))")
            } else {
                lines.append("            return .\(item.name)")
            }
        }
        lines.append("        default: throw DecodeError(kind: .badUnion, offset: decoder.offset, field: 0)")
        lines.append("        }")
        lines.append("    }")
        lines.append("    public static var schemaJSON: String { \(swiftLiteral(emitSchemaJSON(pool, root: id))) }")
        lines.append("    public static func fromResolved(_ value: AvroValue) throws -> \(name) {")
        lines.append("        let (index, payload) = try AvroResolved.union(value)")
        lines.append("        switch index {")
        for item in cases {
            lines.append("        case \(item.index):")
            if item.type != nil {
                lines.append(contentsOf: try resolvedLines(item.typeId, valueExpr: "payload", dest: "resolved", indent: "            ", owner: owner))
                lines.append("            return .\(item.name)(\(boxWrap(item.typeId, expr: "resolved", owner: owner)))")
            } else {
                lines.append("            try AvroResolved.null(payload)")
                lines.append("            return .\(item.name)")
            }
        }
        lines.append("        default: throw DecodeError(kind: .badUnion, offset: 0, field: 0)")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    func encodeLines(_ id: Int, expr: String, indent: String, owner: Int?) throws -> [String] {
        let node = pool.nodes[id]
        if let info = optionalInfo(id) {
            let inner = valueOf(info.valueId, expr: "wrapped", owner: owner)
            var lines = ["\(indent)if let wrapped = \(expr) {", "\(indent)    encoder.writeLong(\(info.valueIndex))"]
            lines.append(contentsOf: try encodeLines(info.valueId, expr: inner, indent: indent + "    ", owner: owner))
            lines.append("\(indent)} else {")
            lines.append("\(indent)    encoder.writeLong(\(info.nullIndex))")
            lines.append("\(indent)}")
            return lines
        }
        switch node.kind {
        case .null:
            return []
        case .boolean:
            return ["\(indent)encoder.writeBool(\(expr))"]
        case .int:
            return ["\(indent)encoder.writeInt(\(expr))"]
        case .long:
            return ["\(indent)encoder.writeLong(\(expr))"]
        case .float:
            return ["\(indent)encoder.writeFloat(\(expr))"]
        case .double:
            return ["\(indent)encoder.writeDouble(\(expr))"]
        case .bytes:
            return ["\(indent)encoder.writeBytes(\(expr))"]
        case .string:
            return ["\(indent)encoder.writeString(\(expr))"]
        case .array:
            var lines = [
                "\(indent)if \(expr).isEmpty {",
                "\(indent)    encoder.writeLong(0)",
                "\(indent)} else {",
                "\(indent)    encoder.writeLong(Int64(\(expr).count))",
                "\(indent)    for element in \(expr) {",
            ]
            lines.append(contentsOf: try encodeLines(node.itemId, expr: valueOf(node.itemId, expr: "element", owner: owner), indent: indent + "        ", owner: owner))
            lines.append("\(indent)    }")
            lines.append("\(indent)    encoder.writeLong(0)")
            lines.append("\(indent)}")
            return lines
        case .map:
            let inner = valueOf(node.valueId, expr: "item", owner: owner)
            var lines = [
                "\(indent)do {",
                "\(indent)    let keys = \(expr).keys.sorted()",
                "\(indent)    if keys.isEmpty {",
                "\(indent)        encoder.writeLong(0)",
                "\(indent)    } else {",
                "\(indent)        encoder.writeLong(Int64(keys.count))",
                "\(indent)        for key in keys {",
                "\(indent)            encoder.writeString(key)",
                "\(indent)            let item = \(expr)[key]!",
            ]
            lines.append(contentsOf: try encodeLines(node.valueId, expr: inner, indent: indent + "            ", owner: owner))
            lines.append("\(indent)        }")
            lines.append("\(indent)        encoder.writeLong(0)")
            lines.append("\(indent)    }")
            lines.append("\(indent)}")
            return lines
        case .union, .record, .enumeration, .fixed:
            return ["\(indent)\(expr).encode(into: &encoder)"]
        }
    }

    func lengthLines(_ id: Int, expr: String, indent: String, owner: Int?) throws -> [String] {
        let node = pool.nodes[id]
        if let info = optionalInfo(id) {
            let inner = valueOf(info.valueId, expr: "wrapped", owner: owner)
            var lines = ["\(indent)if let wrapped = \(expr) {", "\(indent)    total += AvroBinary.longLength(\(info.valueIndex))"]
            lines.append(contentsOf: try lengthLines(info.valueId, expr: inner, indent: indent + "    ", owner: owner))
            lines.append("\(indent)} else {")
            lines.append("\(indent)    total += AvroBinary.longLength(\(info.nullIndex))")
            lines.append("\(indent)}")
            return lines
        }
        switch node.kind {
        case .null:
            return []
        case .boolean:
            return ["\(indent)total += 1"]
        case .int:
            return ["\(indent)total += AvroBinary.intLength(\(expr))"]
        case .long:
            return ["\(indent)total += AvroBinary.longLength(\(expr))"]
        case .float:
            return ["\(indent)total += 4"]
        case .double:
            return ["\(indent)total += 8"]
        case .bytes:
            return ["\(indent)total += AvroBinary.bytesLength(count: \(expr).count)"]
        case .string:
            return ["\(indent)total += AvroBinary.stringLength(\(expr))"]
        case .fixed:
            return ["\(indent)total += \(node.size)"]
        case .array:
            var lines = [
                "\(indent)if \(expr).isEmpty {",
                "\(indent)    total += 1",
                "\(indent)} else {",
                "\(indent)    total += AvroBinary.longLength(Int64(\(expr).count))",
                "\(indent)    for element in \(expr) {",
            ]
            lines.append(contentsOf: try lengthLines(node.itemId, expr: valueOf(node.itemId, expr: "element", owner: owner), indent: indent + "        ", owner: owner))
            lines.append("\(indent)    }")
            lines.append("\(indent)    total += 1")
            lines.append("\(indent)}")
            return lines
        case .map:
            let inner = valueOf(node.valueId, expr: "item", owner: owner)
            var lines = [
                "\(indent)do {",
                "\(indent)    let keys = \(expr).keys.sorted()",
                "\(indent)    if keys.isEmpty {",
                "\(indent)        total += 1",
                "\(indent)    } else {",
                "\(indent)        total += AvroBinary.longLength(Int64(keys.count))",
                "\(indent)        for key in keys {",
                "\(indent)            total += AvroBinary.stringLength(key)",
                "\(indent)            let item = \(expr)[key]!",
            ]
            lines.append(contentsOf: try lengthLines(node.valueId, expr: inner, indent: indent + "            ", owner: owner))
            lines.append("\(indent)        }")
            lines.append("\(indent)        total += 1")
            lines.append("\(indent)    }")
            lines.append("\(indent)}")
            return lines
        case .union, .record, .enumeration:
            return ["\(indent)total += \(expr).encodedByteLength()"]
        }
    }

    func decodeLines(_ id: Int, dest: String, indent: String, owner: Int?) throws -> [String] {
        let node = pool.nodes[id]
        if let info = optionalInfo(id) {
            let index = fresh("index")
            let innerDest = fresh("inner")
            var lines = [
                "\(indent)let \(index) = try decoder.readLong()",
                "\(indent)let \(dest): \(rendered(id, owner: owner))",
                "\(indent)if \(index) == \(info.nullIndex) {",
                "\(indent)    \(dest) = nil",
                "\(indent)} else if \(index) == \(info.valueIndex) {",
            ]
            lines.append(contentsOf: try decodeLines(info.valueId, dest: innerDest, indent: indent + "    ", owner: owner))
            let stored = boxWrap(info.valueId, expr: innerDest, owner: owner)
            lines.append("\(indent)    \(dest) = \(stored)")
            lines.append("\(indent)} else {")
            lines.append("\(indent)    throw DecodeError(kind: .badUnion, offset: decoder.offset, field: 0)")
            lines.append("\(indent)}")
            return lines
        }
        switch node.kind {
        case .null:
            return ["\(indent)let \(dest) = AvroNull()"]
        case .boolean:
            return ["\(indent)let \(dest) = try decoder.readBool()"]
        case .int:
            return ["\(indent)let \(dest) = try decoder.readInt()"]
        case .long:
            return ["\(indent)let \(dest) = try decoder.readLong()"]
        case .float:
            return ["\(indent)let \(dest) = try decoder.readFloat()"]
        case .double:
            return ["\(indent)let \(dest) = try decoder.readDouble()"]
        case .bytes:
            return ["\(indent)let \(dest) = try decoder.readBytes()"]
        case .string:
            return ["\(indent)let \(dest) = try decoder.readString()"]
        case .array:
            let element = rendered(node.itemId, owner: owner)
            let item = fresh("item")
            var lines = [
                "\(indent)var \(dest): [\(element)] = []",
                "\(indent)while true {",
                "\(indent)    let blockCount = try decoder.readBlockCount()",
                "\(indent)    if blockCount == 0 { break }",
                "\(indent)    for _ in 0..<blockCount {",
            ]
            lines.append(contentsOf: try decodeLines(node.itemId, dest: item, indent: indent + "        ", owner: owner))
            lines.append("\(indent)        \(dest).append(\(boxWrap(node.itemId, expr: item, owner: owner)))")
            lines.append("\(indent)    }")
            lines.append("\(indent)    try decoder.endBlock()")
            lines.append("\(indent)}")
            return lines
        case .map:
            let element = rendered(node.valueId, owner: owner)
            let item = fresh("item")
            var lines = [
                "\(indent)var \(dest): [String: \(element)] = [:]",
                "\(indent)while true {",
                "\(indent)    let blockCount = try decoder.readBlockCount()",
                "\(indent)    if blockCount == 0 { break }",
                "\(indent)    for _ in 0..<blockCount {",
                "\(indent)        let mapKey = try decoder.readString()",
            ]
            lines.append(contentsOf: try decodeLines(node.valueId, dest: item, indent: indent + "        ", owner: owner))
            lines.append("\(indent)        \(dest)[mapKey] = \(boxWrap(node.valueId, expr: item, owner: owner))")
            lines.append("\(indent)    }")
            lines.append("\(indent)    try decoder.endBlock()")
            lines.append("\(indent)}")
            return lines
        case .union:
            let union = unionNames[id] ?? typeName(id)
            return ["\(indent)let \(dest) = try \(union).decode(from: &decoder)"]
        case .record, .enumeration, .fixed:
            return ["\(indent)let \(dest) = try \(typeName(id)).decode(from: &decoder)"]
        }
    }

    func resolvedLines(_ id: Int, valueExpr: String, dest: String, indent: String, owner: Int?) throws -> [String] {
        let node = pool.nodes[id]
        if let info = optionalInfo(id) {
            let parts = fresh("parts")
            let inner = fresh("inner")
            var lines = [
                "\(indent)let \(parts) = try AvroResolved.union(\(valueExpr))",
                "\(indent)let \(dest): \(rendered(id, owner: owner))",
                "\(indent)if \(parts).0 == \(info.nullIndex) {",
                "\(indent)    try AvroResolved.null(\(parts).1)",
                "\(indent)    \(dest) = nil",
                "\(indent)} else {",
            ]
            lines.append(contentsOf: try resolvedLines(info.valueId, valueExpr: "\(parts).1", dest: inner, indent: indent + "    ", owner: owner))
            lines.append("\(indent)    \(dest) = \(boxWrap(info.valueId, expr: inner, owner: owner))")
            lines.append("\(indent)}")
            return lines
        }
        switch node.kind {
        case .null:
            return ["\(indent)try AvroResolved.null(\(valueExpr))", "\(indent)let \(dest) = AvroNull()"]
        case .boolean:
            return ["\(indent)let \(dest) = try AvroResolved.bool(\(valueExpr))"]
        case .int:
            return ["\(indent)let \(dest) = try AvroResolved.int32(\(valueExpr))"]
        case .long:
            return ["\(indent)let \(dest) = try AvroResolved.int64(\(valueExpr))"]
        case .float:
            return ["\(indent)let \(dest) = try AvroResolved.float32(\(valueExpr))"]
        case .double:
            return ["\(indent)let \(dest) = try AvroResolved.float64(\(valueExpr))"]
        case .bytes:
            return ["\(indent)let \(dest) = try AvroResolved.bytes(\(valueExpr))"]
        case .string:
            return ["\(indent)let \(dest) = try AvroResolved.string(\(valueExpr))"]
        case .enumeration:
            return ["\(indent)let \(dest) = try \(typeName(id)).fromResolved(\(valueExpr))"]
        case .fixed:
            return ["\(indent)let \(dest) = try \(typeName(id)).fromResolved(\(valueExpr))"]
        case .record:
            return ["\(indent)let \(dest) = try \(typeName(id)).fromResolved(\(valueExpr))"]
        case .array:
            let raw = fresh("items")
            let item = fresh("item")
            var lines = [
                "\(indent)let \(raw) = try AvroResolved.array(\(valueExpr))",
                "\(indent)var \(dest): [\(rendered(node.itemId, owner: owner))] = []",
                "\(indent)\(dest).reserveCapacity(\(raw).count)",
                "\(indent)for value in \(raw) {",
            ]
            lines.append(contentsOf: try resolvedLines(node.itemId, valueExpr: "value", dest: item, indent: indent + "    ", owner: owner))
            lines.append("\(indent)    \(dest).append(\(boxWrap(node.itemId, expr: item, owner: owner)))")
            lines.append("\(indent)}")
            return lines
        case .map:
            let raw = fresh("pairs")
            let item = fresh("item")
            var lines = [
                "\(indent)let \(raw) = try AvroResolved.map(\(valueExpr))",
                "\(indent)var \(dest): [String: \(rendered(node.valueId, owner: owner))] = [:]",
                "\(indent)for pair in \(raw) {",
            ]
            lines.append(contentsOf: try resolvedLines(node.valueId, valueExpr: "pair.1", dest: item, indent: indent + "    ", owner: owner))
            lines.append("\(indent)    \(dest)[pair.0] = \(boxWrap(node.valueId, expr: item, owner: owner))")
            lines.append("\(indent)}")
            return lines
        case .union:
            let union = unionNames[id] ?? "AvroRootUnion"
            return ["\(indent)let \(dest) = try \(union).fromResolved(\(valueExpr))"]
        }
    }

    func zero(_ id: Int, owner: Int?) throws -> String {
        let node = pool.nodes[id]
        if optionalInfo(id) != nil { return "nil" }
        switch node.kind {
        case .null: return "AvroNull()"
        case .boolean: return "false"
        case .int, .long: return "0"
        case .float, .double: return "0"
        case .bytes: return "[]"
        case .string: return "\"\""
        case .array: return "[]"
        case .map: return "[:]"
        case .enumeration, .fixed, .record:
            return "\(typeName(id))()"
        case .union:
            return "\(unionNames[id] ?? "AvroRootUnion")()"
        }
    }

    func rendered(_ id: Int, owner: Int?) -> String {
        if isBox(id, owner: owner) {
            return "Box<\(typeName(id))>"
        }
        let node = pool.nodes[id]
        switch node.kind {
        case .null: return "AvroNull"
        case .boolean: return "Bool"
        case .int: return "Int32"
        case .long: return "Int64"
        case .float: return "Float"
        case .double: return "Double"
        case .bytes: return "[UInt8]"
        case .string: return "String"
        case .array: return "[\(rendered(node.itemId, owner: owner))]"
        case .map: return "[String: \(rendered(node.valueId, owner: owner))]"
        case .union:
            if optionalInfo(id) != nil {
                return rendered(optionalInfo(id)!.valueId, owner: owner) + "?"
            }
            return unionNames[id] ?? "AvroRootUnion"
        case .record, .enumeration, .fixed:
            return typeName(id)
        }
    }

    func isBox(_ id: Int, owner: Int?) -> Bool {
        guard let owner else { return false }
        guard pool.nodes[id].kind == .record else { return false }
        return scc[owner]?.contains(id) ?? false
    }

    func valueOf(_ id: Int, expr: String, owner: Int?) -> String {
        isBox(id, owner: owner) ? "\(expr).value" : expr
    }

    func boxWrap(_ id: Int, expr: String, owner: Int?) -> String {
        isBox(id, owner: owner) ? "Box(\(expr))" : expr
    }

    func branchRecursive(_ id: Int, owner: Int?) -> Bool {
        isBox(id, owner: owner)
    }

    func optionalInfo(_ id: Int) -> (nullIndex: Int, valueIndex: Int, valueId: Int)? {
        let node = pool.nodes[id]
        guard node.kind == .union, node.branchIds.count == 2 else { return nil }
        let first = pool.nodes[node.branchIds[0]].kind
        let second = pool.nodes[node.branchIds[1]].kind
        if first == .null { return (0, 1, node.branchIds[1]) }
        if second == .null { return (1, 0, node.branchIds[0]) }
        return nil
    }

    func typeName(_ id: Int) -> String {
        let node = pool.nodes[id]
        let raw = node.name.isEmpty ? (node.shortName.isEmpty ? "AvroType\(id)" : node.shortName) : node.name
        let parts = raw.split(separator: ".").map { typePiece(String($0)) }
        return parts.joined(separator: "_")
    }

    func typePiece(_ name: String) -> String {
        var text = name
        if swiftKeywords.contains(text) { text += "_" }
        return text
    }

    func fieldIdent(_ name: String) -> String {
        swiftKeywords.contains(name) ? "`\(name)`" : name
    }

    func caseIdent(_ symbol: String) -> String {
        let cleaned = symbol.unicodeScalars.map { scalar -> Character in
            if (scalar >= "A" && scalar <= "Z") || (scalar >= "a" && scalar <= "z") || (scalar >= "0" && scalar <= "9") || scalar == "_" {
                return Character(scalar)
            }
            return "_"
        }
        var text = String(cleaned)
        if text.isEmpty { text = "symbol" }
        if text.first?.isNumber == true { text = "_" + text }
        if swiftKeywords.contains(text) { return "`\(text)`" }
        return text
    }

    func freshCase(_ id: Int, index: Int, used: inout Set<String>) -> String {
        let node = pool.nodes[id]
        let base: String
        switch node.kind {
        case .record, .enumeration, .fixed:
            let short = node.shortName.isEmpty ? shortName(of: node.name) : node.shortName
            base = lowerFirst(typePiece(short))
        case .null:
            base = "null"
        default:
            base = primitiveToken(node.kind) ?? "branch"
        }
        var name = base
        if used.contains(name) { name = base + String(index) }
        used.insert(name)
        if swiftKeywords.contains(name) { name = "`\(name)`" }
        return name
    }

    func lowerFirst(_ text: String) -> String {
        guard let first = text.first else { return text }
        return first.lowercased() + text.dropFirst()
    }

    func fresh(_ prefix: String) -> String {
        serial += 1
        return prefix + String(serial)
    }

    func swiftLiteral(_ text: String) -> String {
        var out = "\""
        for scalar in text.unicodeScalars {
            switch scalar.value {
            case 0x5c: out += "\\\\"
            case 0x22: out += "\\\""
            case 0x0a: out += "\\n"
            case 0x0d: out += "\\r"
            case 0x09: out += "\\t"
            case let value where value < 0x20:
                out += "\\u{\(String(value, radix: 16))}"
            default:
                out.unicodeScalars.append(scalar)
            }
        }
        out += "\""
        return out
    }
}

func strongComponents(_ pool: SchemaPool) -> [Int: Set<Int>] {
    var index = 0
    var stack: [Int] = []
    var onStack = Set<Int>()
    var indices: [Int: Int] = [:]
    var low: [Int: Int] = [:]
    var groups: [[Int]] = []

    func targets(_ id: Int) -> [Int] {
        let node = pool.nodes[id]
        switch node.kind {
        case .record: return [id]
        case .array: return targets(node.itemId)
        case .map: return targets(node.valueId)
        case .union: return node.branchIds.flatMap { targets($0) }
        default: return []
        }
    }

    func walk(_ id: Int) {
        indices[id] = index
        low[id] = index
        index += 1
        stack.append(id)
        onStack.insert(id)
        for next in pool.nodes[id].fields.flatMap({ targets($0.typeId) }) where pool.nodes[next].kind == .record {
            if indices[next] == nil {
                walk(next)
                low[id] = min(low[id]!, low[next]!)
            } else if onStack.contains(next) {
                low[id] = min(low[id]!, indices[next]!)
            }
        }
        if low[id] == indices[id] {
            var group: [Int] = []
            while true {
                let item = stack.removeLast()
                onStack.remove(item)
                group.append(item)
                if item == id { break }
            }
            groups.append(group)
        }
    }

    for (id, node) in pool.nodes.enumerated() where node.kind == .record && node.complete && indices[id] == nil {
        walk(id)
    }
    var result: [Int: Set<Int>] = [:]
    for group in groups {
        let set = Set(group)
        for id in group { result[id] = set }
    }
    return result
}
